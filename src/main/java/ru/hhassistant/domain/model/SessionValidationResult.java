package ru.hhassistant.domain.model;

/**
 * Результат проверки сессии hh.ru перед началом polling-цикла.
 *
 * Принципиально важно различать два «плохих» случая:
 * - INVALID: токен/cookie протух, нужна повторная авторизация пользователя.
 * - TEMP_UNAVAILABLE: сам hh.ru недоступен (5xx, таймаут, antibot-страница);
 *   токен при этом может быть валидным — прерывать сессию нельзя.
 */
public enum SessionValidationResult {

    /** Сессия активна, можно выполнять запросы. */
    VALID,

    /**
     * Сессия невалидна: редирект на login, HTTP 401/403, маркеры истечения сессии.
     * Пользователю нужно войти заново.
     */
    INVALID,

    /**
     * Временная недоступность hh.ru: таймаут, transport error, HTTP 5xx, 429,
     * antibot/captcha-страница. Сессия может быть живой — повторить позже.
     */
    TEMP_UNAVAILABLE
}
